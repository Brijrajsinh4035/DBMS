FROM EMPLOYEE_MASTER E
LEFT JOIN EMPLOYEE_MASTER M
ON E.MANAGERNO = M.EMPLOYEENO
LEFT JOIN EMPLOYEE_MASTER S
ON M.MANAGERNO = S.EMPLOYEENO

