CREATE TABLE STUDENT_INFO
(
	RNO INT PRIMARY KEY IDENTITY(101,1),
	NAME VARCHAR(20) NOT NULL,
	BRANCH VARCHAR(20) DEFAULT('CE')
)

CREATE TABLE RESULT
(
	RESULTID INT IDENTITY(11,1),
	SPI DECIMAL(4,2) CHECK(SPI BETWEEN 0 AND 10),
	RNO INT,

	CONSTRAINT PK_RESULT_RESULTID
	PRIMARY KEY (RESULTID),

	CONSTRAINT FK_RESULT_RNO
	FOREIGN KEY(RNO) REFERENCES STUDENT_INFO(RNO)
)

