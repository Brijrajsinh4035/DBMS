CREATE TABLE PUBLISHER
(
	PUBLISHERID INT PRIMARY KEY IDENTITY(1,1),
	PUBLISHERNAME VARCHAR(100) NOT NULL,
	CITY VARCHAR(50) NOT NULL

	CONSTRAINT UK_PULISHER_PUBLISHERNAME
	UNIQUE(PUBLISHERNAME)
)

CREATE TABLE AUTHOR
(
	AUTHORID INT PRIMARY KEY IDENTITY(1,1),
	AUTHORNAME VARCHAR(100) NOT NULL,
	COUNTRY VARCHAR(50)
)

CREATE TABLE BOOK
(
	BOOKID INT PRIMARY KEY IDENTITY(101,1),
	TITLE VARCHAR(200) NOT NULL,
	AUTHORID INT NOT NULL FOREIGN KEY REFERENCES AUTHOR(AUTHORID),
	PUBLISHERID INT NOT NULL FOREIGN KEY REFERENCES PUBLISHER(PUBLISHERID),
	PRICE DECIMAL(8,2) NOT NULL,
	PUBLICATIONYEAR INT NOT NULL
)


