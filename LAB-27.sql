DECLARE
    @FIRSTNAME VARCHAR(50),
    @LASTNAME VARCHAR(50),
    @DEPARTMENT VARCHAR(50),
    @SALARY DECIMAL(10,2);

DECLARE Above_Avg_Cursor CURSOR LOCAL FAST_FORWARD READ_ONLY
FOR
    SELECT E.FIRSTNAME, E.LASTNAME, E.DEPARTMENT, E.SALARY
    FROM EMPLOYEE E
    WHERE E.SALARY > (SELECT AVG(E2.SALARY)
                      FROM EMPLOYEE E2
                      WHERE E2.DEPARTMENT = E.DEPARTMENT); 

OPEN Above_Avg_Cursor;
FETCH NEXT FROM Above_Avg_Cursor INTO @FIRSTNAME, @LASTNAME, @DEPARTMENT, @SALARY;

WHILE @@FETCH_STATUS = 0
BEGIN
    PRINT CONCAT(@FIRSTNAME, ' ', @LASTNAME, ' | ', @DEPARTMENT, ' | Salary: ', @SALARY);

    FETCH NEXT FROM Above_Avg_Cursor INTO @FIRSTNAME, @LASTNAME, @DEPARTMENT, @SALARY;
END

CLOSE Above_Avg_Cursor;
DEALLOCATE Above_Avg_Cursor;
GO

