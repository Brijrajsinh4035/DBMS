WITH SAME_SPI_COUNT AS(
	SELECT *,
	RANK() OVER(ORDER BY SPI) AS RANK,
	COUNT(*) OVER(PARTITION BY SPI)AS COUNT_SPI
	FROM STUDENT
)
SELECT * FROM SAME_SPI_COUNT
WHERE COUNT_SPI >= 2
ORDER BY SPI DESC,STDID

