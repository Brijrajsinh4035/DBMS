SPI AS 'CURRENT SPI',
LEAD(SPI) OVER(ORDER BY SPI,STDID) AS 'NEXT SPI'
FROM STUDENT
ORDER BY SPI,STDID

--15
WITH TOPPER_BRANCH AS(
	SELECT *,DENSE_RANK() OVER(PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK
	FROM STUDENT
)
SELECT * FROM TOPPER_BRANCH
WHERE RANK = 1

--16
WITH PREV_NEXT_SPI AS(
	SELECT SNAME,LAG(SPI) OVER(ORDER BY SPI) AS 'PREVIOUS_SPI',
	SPI AS 'CURRENT_SPI',
	LEAD(SPI) OVER(ORDER BY SPI) AS 'NEXT_SPI'
	FROM STUDENT
)
SELECT SNAME,PREVIOUS_SPI,CURRENT_SPI,NEXT_SPI
FROM PREV_NEXT_SPI
WHERE CURRENT_SPI>PREVIOUS_SPI AND CURRENT_SPI<NEXT_SPI
ORDER BY CURRENT_SPI

--17
