--18
WITH RANK_DENSE_RANK AS(
	SELECT *,
	RANK() OVER(ORDER BY SPI DESC) AS 'RANK',
	DENSE_RANK() OVER(ORDER BY SPI DESC) AS 'DENSE'
	FROM STUDENT
)
SELECT * FROM RANK_DENSE_RANK
WHERE RANK <> DENSE
ORDER BY RANK,STDID

--19
WITH NEXT_BRANCH AS(
	SELECT *,LAG(BRANCH) OVER(ORDER BY SPI) AS P_BRANCH,
	LEAD(BRANCH) OVER(ORDER BY SPI) AS N_BRANCH
	FROM STUDENT
)
SELECT * FROM NEXT_BRANCH
WHERE BRANCH = P_BRANCH OR BRANCH = N_BRANCH
ORDER BY SPI

--20
WITH PREV_DIFF AS(
SELECT *,(SPI-LAG(SPI) OVER(ORDER BY STDID)) AS DIFF_PREV
FROM STUDENT
)
SELECT TOP 1 WITH TIES  STDID, SNAME, SPI, DIFF_PREV FROM PREV_DIFF
ORDER BY DIFF_PREV DESC

