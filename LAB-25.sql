ALTER FUNCTION EMPLOYEEALL(@ID INT)
RETURNS VARCHAR(50)
AS
BEGIN
	DECLARE @FIRSTNAME VARCHAR(50);
	DECLARE @DEP VARCHAR(50);

	SELECT @FIRSTNAME = FIRSTNAME,@DEP = DEPARTMENT  FROM EMPLOYEE
	WHERE EID = @ID;
	RETURN @FIRSTNAME+' IS '+@DEP+' DEPARTMENT EMPLOYEE'
END

