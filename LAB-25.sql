CREATE FUNCTION MAXINTHREE(@A INT,@B INT,@C INT)
RETURNS VARCHAR(50)
AS
BEGIN
	IF(@A>@B AND @A>@C)
	BEGIN
		RETURN CONCAT(@A,' IS MAX');
	END
	ELSE IF(@B>@A AND @B>@C)
	BEGIN
		RETURN CONCAT(@B,' IS MAX');
	END
	RETURN CONCAT(@C,' IS MAX');
END

SELECT DBO.MAXINTHREE(1000,-3000,-3000)

