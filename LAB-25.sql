ALTER FUNCTION PRINT1TON(@N INT)
RETURNS VARCHAR(MAX)
AS
BEGIN
	DECLARE @STR VARCHAR(MAX)
	DECLARE @I INT=1;
	WHILE(@I<=@N)
	BEGIN
		SET @STR = CONCAT(@STR,' ',@I)
		SET @I=@I+1
	END
	RETURN @STR
END

SELECT DBO.PRINT1TON(10)

