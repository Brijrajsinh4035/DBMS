CREATE FUNCTION PALINDROME(@N INT)
RETURNS VARCHAR(50)
AS
BEGIN
	DECLARE @REM INT=0,@REV INT=0,@TEMP INT=@N;
	WHILE(@N>0)
	BEGIN
		SET @REM = @N%10
		SET @REV = @REV * 10 + @REM;
		SET @N = @N / 10
	END
	IF(@REV=@TEMP)
	BEGIN
		RETURN CONCAT(@TEMP,' IS PALINDROME')
	END
	RETURN CONCAT(@TEMP,' IS NOT PALINDROME')
END

SELECT DBO.PALINDROME(12)

