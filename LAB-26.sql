--14
CREATE FUNCTION STUDENT_STDID(@STDID INT)
RETURNS TABLE
AS
RETURN (
	WITH CTE AS(
		SELECT RANK() OVER(ORDER BY SPI DESC) 'RANK',* 
		FROM STUDENT
	)
	SELECT * FROM CTE
	WHERE STDID = @STDID
)
SELECT * FROM STUDENT_STDID(105)

