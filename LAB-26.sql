ALTER FUNCTION STUDENT_BETWEEN(@MAX DECIMAL(4,2),@MIN DECIMAL(4,2))
RETURNS TABLE
AS 
	RETURN (
		SELECT * FROM STUDENT
		WHERE SPI >= @MIN AND SPI <= @MAX
	)

