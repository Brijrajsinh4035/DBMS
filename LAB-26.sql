--2
CREATE FUNCTION STUDENT_CITY(@CITY VARCHAR(50))
RETURNS TABLE
AS
	RETURN (SELECT * FROM STUDENT
		WHERE CITY=@CITY
	)

SELECT * FROM STUDENT_CITY('RAJKOT')

