--9
CREATE FUNCTION STUDENT_TOP(@TOPN INT)
RETURNS TABLE
AS
RETURN(
	SELECT TOP (@TOPN) * FROM STUDENT
	ORDER BY SPI DESC
)

SELECT * FROM STUDENT_TOP(3)

--10
ALTER FUNCTION STUDENT_HIGH_SPI(@BRANCH VARCHAR(50))
RETURNS TABLE
AS
RETURN(
	SELECT DISTINCT MAX(SPI) OVER(PARTITION BY @BRANCH) 'HIGH' FROM STUDENT
	WHERE BRANCH = @BRANCH
)

SELECT * FROM STUDENT_HIGH_SPI('CIVIL')

--11
ALTER FUNCTION STUDENT_CITY_TOTAL(@CITY VARCHAR(50))
RETURNS TABLE
AS
RETURN (
	SELECT DISTINCT COUNT(CITY) OVER() 'COUNT' FROM STUDENT
	WHERE CITY = @CITY
)

SELECT * FROM STUDENT_CITY_TOTAL('RAJKOT')

