CREATE FUNCTION STUDENT_SPI(@SPI DECIMAL(4,2))
RETURNS TABLE
AS
	RETURN (
		SELECT * FROM STUDENT
		WHERE SPI>@SPI
	)

SELECT * FROM STUDENT_SPI(8)

