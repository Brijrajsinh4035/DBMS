CREATE PROC PR_PUBLISHER_BOOKCOUNT
	@PUBLISHER VARCHAR(50)
AS
BEGIN
	SELECT P.PUBLISHERNAME,COUNT(B.BOOKID) 'BOOK COUNT' FROM PUBLISHER P
	LEFT JOIN BOOK B
	ON B.PUBLISHERID =P.PUBLISHERID
	WHERE P.PUBLISHERNAME = @PUBLISHER
	GROUP BY P.PUBLISHERNAME
END
EXEC PR_PUBLISHER_BOOKCOUNT 'RUPA PUBLICATIONS'

