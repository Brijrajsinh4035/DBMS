CREATE PROC PR_AUTHOR_NAME
	@AUTHOR VARCHAR(50)
AS
BEGIN
	SELECT A.AUTHORNAME,B.TITLE
	FROM AUTHOR A
	INNER JOIN BOOK B
	ON A.AUTHORID = B.AUTHORID
	WHERE A.AUTHORNAME = @AUTHOR
END
EXEC PR_AUTHOR_NAME 'CHETAN BHAGAT'

