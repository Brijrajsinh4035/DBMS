ALTER PROC PR_EMPLOYEE_N_HIGH
	@N INT
AS
BEGIN
	WITH CTA AS(
		SELECT *,DENSE_RANK() OVER(PARTITION BY DEPARTMENT ORDER BY SALARY DESC) 'RANK'
		FROM EMPLOYEE
	) SELECT * FROM CTA
	WHERE RANK <= @N
END

EXEC PR_EMPLOYEE_N_HIGH 2

