CREATE PROC PR_EMPLOYEE_DEPARTMENT
	@DEP VARCHAR(50)
AS
BEGIN
	SELECT DEPARTMENT,
		SUM(SALARY) 'TOTAL_SALARY',
		AVG(SALARY) 'AVERAGE SALARY',
		MIN(SALARY) 'MINIMUM SALARY',
		MAX(SALARY) 'MAXIMUM SALARY'
	FROM EMPLOYEE 
	WHERE DEPARTMENT = @DEP
	GROUP BY DEPARTMENT
END

EXEC PR_EMPLOYEE_DEPARTMENT IT

