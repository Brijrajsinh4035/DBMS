ALTER PROC PR_BOOK_PRICE_RANK
	@N INT
AS
BEGIN
	WITH CTE AS(
		SELECT *,DENSE_RANK() OVER(ORDER BY PRICE DESC) 'RK'
		FROM BOOK
	)SELECT A.AUTHORNAME,P.PUBLISHERNAME,B.TITLE,B.PRICE
	FROM AUTHOR A
	INNER JOIN CTE B
	ON A.AUTHORID = B.AUTHORID
	INNER JOIN PUBLISHER P
	ON P.PUBLISHERID = B.PUBLISHERID
	WHERE B.RK <= @N
END

EXEC PR_BOOK_PRICE_RANK 3

