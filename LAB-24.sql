ALTER PROC PR_EMPLOYEE_SEARCH
	@CITY VARCHAR(50) = NULL,
	@FIRSTNAME VARCHAR(50) = NULL,
	@LASTNAME VARCHAR(50) = NULL,
	@DEPARTMENT VARCHAR(50) = NULL
AS
BEGIN
	SELECT * FROM EMPLOYEE
	WHERE
	(@CITY IS NULL OR CITY LIKE '%'+@CITY+'%')
	AND (@FIRSTNAME IS NULL OR FIRSTNAME LIKE CONCAT('%',@FIRSTNAME,'%'))
	AND (@LASTNAME IS NULL OR LASTNAME LIKE CONCAT('%',@LASTNAME,'%'))
	AND (@DEPARTMENT IS NULL OR DEPARTMENT LIKE CONCAT('%',@DEPARTMENT,'%'))
END

EXEC PR_EMPLOYEE_SEARCH @CITY='RAJ',@DEPARTMENT='ADM'

