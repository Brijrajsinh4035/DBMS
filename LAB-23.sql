CREATE PROC PR_EMPLOYEE_SELECT_MIN_MAX_AVG_DEPARTMENT
	@DEPARTMENT VARCHAR(50)
AS
BEGIN
	SELECT MAX(SALARY) AS 'MAX',MIN(SALARY) AS 'MIN',AVG(SALARY) AS 'AVG'
	FROM EMPLOYEE
	WHERE DEPARTMENT = @DEPARTMENT
END

EXEC PR_EMPLOYEE_SELECT_MIN_MAX_AVG_DEPARTMENT IT

