CREATE PROC PR_STUDENT_INSERT
	@STDID INT,
	@SNAME VARCHAR(50),
	@CITY VARCHAR(50),
	@SPI DECIMAL(4,2),
	@BRANCH VARCHAR(50)
AS
BEGIN
	INSERT INTO STUDENT
	VALUES (@STDID,@SNAME,@CITY,@SPI,@BRANCH)
END

EXEC PR_STUDENT_INSERT 115,'PUSHTI','RAJKOT',9.48,'COMPUTER'
EXEC PR_STUDENT_INSERT @STDID=116,@SNAME='NIKUNJ',@CITY='SURAT',@SPI=8.80,@BRANCH='CHEMICAL'

