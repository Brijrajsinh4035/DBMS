ALTER PROC PR_EMPLOYEE_SUM_SALARY_DEPARTMENT_WISE
	@DEPARTMENT VARCHAR(50)
AS
BEGIN
	SELECT DEPARTMENT,SUM(SALARY) AS 'SUM'
	FROM EMPLOYEE
	WHERE DEPARTMENT=@DEPARTMENT
	GROUP BY DEPARTMENT
END

