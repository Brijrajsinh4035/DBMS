CREATE PROC PR_STUDENT_UPDATE
	@STDID INT,
	@BRANCH VARCHAR(50)
AS
BEGIN
	UPDATE STUDENT
	SET BRANCH = @BRANCH
	WHERE STDID = @STDID
END

EXEC PR_STUDENT_UPDATE 115,'ELECTRICAL'
EXEC PR_STUDENT_UPDATE @STDID=116,@BRANCH='MECHANICAL'

