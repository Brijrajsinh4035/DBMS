WITH HIGH_CATEGORY AS(
    SELECT *,DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC) 'RANK_HIGH'
    FROM CUSTOMER_ALL
)
,LOW_CATEGORY AS(
    SELECT *,DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT) 'RANK_LOW'
    FROM CUSTOMER_ALL
)
SELECT H.*
FROM HIGH_CATEGORY H
JOIN LOW_CATEGORY L
ON H.ORDERID = L.ORDERID
WHERE H.RANK_HIGH<>1 AND L.RANK_LOW<>1

SELECT ORDERID, CNAME, CATEGORY, AMOUNT
FROM (
    SELECT *,
           MAX(AMOUNT) OVER (PARTITION BY CATEGORY) AS MX,
           MIN(AMOUNT) OVER (PARTITION BY CATEGORY) AS MN
    FROM CUSTOMER_ALL
) T
WHERE AMOUNT <> MX AND AMOUNT <> MN;
