--1
SELECT P.PLAYER_FIRST_NAME,S.Stadium_city
FROM PLAYER P
INNER JOIN TEAM T
ON P.TEAM_ID = T.TEAM_ID
INNER JOIN STADIUM S
ON T.HOME_STADIUM_ID = S.Stadium_id
WHERE S.Stadium_city = 'MUMBAI'

--2
SELECT T.TEAM_NAME,P.PLAYER_FIRST_NAME
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
ORDER BY T.TEAM_NAME

--3
SELECT P.PLAYER_FIRST_NAME,T.TEAM_WINS,S.Stadium_city
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
INNER JOIN STADIUM S
ON T.HOME_STADIUM_ID = S.Stadium_id

--4
SELECT T.TEAM_NAME,COUNT(PLAYER_ID) AS 'TOTAL PLAYER'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
GROUP BY T.TEAM_NAME

--5
SELECT T.TEAM_NAME,T.TEAM_COACH,
COUNT(PLAYER_ID) AS 'TOTAL BOLWER'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
WHERE P.PLAYER_ROLE IN ('BOWLER')
GROUP BY T.TEAM_NAME,T.TEAM_COACH

--6
SELECT T.TEAM_NAME,
SUM(CASE WHEN PLAYER_ROLE = 'BATSMAN' THEN 1 END)'BATSMAN',
SUM(CASE WHEN PLAYER_ROLE = 'BOWLER' THEN 1 END)'BOWLER',
SUM(CASE WHEN PLAYER_ROLE = 'ALL-ROUNDER' THEN 1 END)'ALL-ROUNDER'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
GROUP BY T.TEAM_NAME

--7
SELECT S.Stadium_name
FROM STADIUM S
INNER JOIN TEAM T
ON S.Stadium_id = T.HOME_STADIUM_ID
