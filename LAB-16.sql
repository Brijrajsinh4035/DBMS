--8
SELECT T.TEAM_NAME,COUNT(PLAYER_ID) AS 'MORE THAN 25 MATCH PLAYED'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
WHERE P.PLAYER_MATCHES_PLAYED>25
GROUP BY T.TEAM_NAME

--9
SELECT T.TEAM_NAME,COUNT(PLAYER_ID) AS 'MORE THAN 25 MATCH PLAYED'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
WHERE P.PLAYER_JERSEY_NUMBER>30
GROUP BY T.TEAM_NAME

--10
SELECT T.TEAM_NAME,SUM(PLAYER_MATCHES_PLAYED) 'TOTAL MATCHIES PLAYED'
FROM TEAM T
INNER JOIN PLAYER P
ON T.TEAM_ID = P.TEAM_ID
GROUP BY T.TEAM_NAME
ORDER BY T.TEAM_NAME

--11
