CREATE TRIGGER EMPLOYEE_UPDATE_LOG_TABLE
ON EMPLOYEE
AFTER UPDATE
AS
BEGIN
	IF EXISTS(SELECT * FROM inserted I JOIN deleted D
			ON D.EID=I.EID
			WHERE D.SALARY!=I.SALARY OR D.DEPARTMENT != I.DEPARTMENT
			)
	BEGIN
		DECLARE @OLDSALARY DECIMAL(10,2),@NEWSALARY DECIMAL(10,2),
				@OLDDEPARTMENT VARCHAR(50),@NEWDEPARTMENT VARCHAR(50),
				@EID INT;
		SELECT @EID=I.EID,@OLDSALARY=D.SALARY,@NEWSALARY=I.SALARY,
				@OLDDEPARTMENT = D.DEPARTMENT,@NEWDEPARTMENT = I.DEPARTMENT
		FROM inserted I 
		INNER JOIN deleted D
		ON I.EID = D.EID

		INSERT INTO EMPLOYEE_UPDATE_LOG
		VALUES(@EID,@OLDSALARY,@NEWSALARY,@OLDDEPARTMENT,@NEWDEPARTMENT,DEFAULT)

		PRINT 'EMPLOYEE_UPDATE_LOG INSERTED TOG'
	END
END

